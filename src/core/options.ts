// 地图模块 · 模块级可调项
//
// ⚠️ 合规提醒：`showAttribution` 控制底图版权署名（地图右下角）。
//    Esri World Imagery 的使用条款通常要求保留署名
//    （Esri, Maxar, Earthstar Geographics, and the GIS User Community）。
//    设为 false 只是让界面更整洁，**合规责任由使用方承担**；
//    需要恢复署名时把下面这一项改回 true 即可（无需改动其它任何文件）。
export const MAP_OPTIONS = {
  /** 是否在地图右下角显示底图版权署名 */
  showAttribution: false,

  /** 显示署名时的紧凑模式（鼠标悬停展开完整署名） */
  compactAttribution: true,

  /**
   * 栅格瓦片淡入时长（毫秒）。
   * 0 = 关闭淡入：瓦片下载完成即刻显示，拖动时"低清叠底 → 高清"的替换是瞬时的，
   * 不会在中途露出底色（黑框）。需要老版本的柔和淡入效果时改回 300 即可。
   */
  rasterFadeDuration: 0,

  /**
   * 全球低精度"地板层"预热到的最大层级（见 core/preload.ts）。
   * 5 = z0–5 共 1,365 张 / 约 10.8 MB（局域网实测 ≈ 0.4–0.9 s）。
   *
   * 为什么是 5（实测，同一套"缩到最小 + 来回拖"动作，统计整屏底色的帧数）：
   *   z0–4 → 16 帧空白，最长 358 ms（缩小过程中会经过 z5，该档没有地板层）
   *   z0–5 → 0 帧空白
   *   z0–6 → 0 帧空白（比 z5 多 27 MB / 多约 1 秒，无额外收益）
   * 即 z5 就是这条曲线的拐点。宿主瓦片只有更低层级时，把这里调到实际拥有的最深层级。
   * 设为 0 表示不预热；设为 -1 表示由宿主自行决定（不读取本项）。
   */
  preloadMaxZoom: 5,

  /** 预热的并发数（8 已接近局域网服务端吞吐上限，再大单张反而变慢） */
  preloadConcurrency: 8,

  /**
   * 宿主进入地图后是否**自动**预热一次（独立宿主用；主系统由启动页显式调用）。
   * 关掉后独立宿主只保留"预热全球底图"按钮，手动触发。
   */
  preloadOnEnter: true,

  /**
   * 自动预热前的等待时间（毫秒）：先让地图自己的首屏瓦片抢到连接，
   * 避免刚进页面时"地图加载"和"预热 341 张"互相争抢。
   */
  preloadAutoDelayMs: 1200,
}

export type MapOptions = typeof MAP_OPTIONS
